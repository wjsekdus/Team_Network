-- 경찰과 도둑 초기 스키마
-- PostgreSQL 과 H2(MODE=PostgreSQL, 테스트용) 양쪽에서 동작하도록 표준 SQL 위주로 작성했다.
-- 이미 적용된 마이그레이션 파일은 절대 수정하지 말고, 변경은 V2__... 처럼 새 파일로 추가한다.
-- 설명: docs/architecture/DATABASE.md

-- 사용자(게스트 계정). 닉네임은 중복 허용, 식별은 id 로만 한다.
CREATE TABLE users (
    id              UUID PRIMARY KEY,
    nickname        VARCHAR(20)              NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    last_active_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 서버 발급 인증 토큰. 토큰 원문은 저장하지 않고 SHA-256(hex) 해시만 저장한다.
CREATE TABLE auth_tokens (
    token_hash  CHAR(64) PRIMARY KEY,
    user_id     UUID                     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at  TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_auth_tokens_user ON auth_tokens (user_id);

-- 경기. 상태(status)와 결과(result)를 분리해 저장한다.
CREATE TABLE games (
    id                UUID PRIMARY KEY,
    status            VARCHAR(16)              NOT NULL,
    center_latitude   DOUBLE PRECISION         NOT NULL,
    center_longitude  DOUBLE PRECISION         NOT NULL,
    current_radius_m  DOUBLE PRECISION         NOT NULL,
    jail_radius_m     DOUBLE PRECISION         NOT NULL DEFAULT 10,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    starts_at         TIMESTAMP WITH TIME ZONE,
    started_at        TIMESTAMP WITH TIME ZONE,
    ends_at           TIMESTAMP WITH TIME ZONE,
    ended_at          TIMESTAMP WITH TIME ZONE,
    result            VARCHAR(16),
    end_reason        VARCHAR(40),
    CONSTRAINT chk_games_status CHECK (status IN ('READY', 'PLAYING', 'FINISHED', 'CANCELLED')),
    CONSTRAINT chk_games_result CHECK (result IS NULL OR result IN ('POLICE_WIN', 'THIEF_WIN', 'INVALID'))
);
CREATE INDEX idx_games_status ON games (status);

-- 경기 참가자(경기 x 사용자). 역할, 플레이어 상태, 접속 상태를 따로 관리한다.
CREATE TABLE game_players (
    game_id           UUID                     NOT NULL REFERENCES games (id) ON DELETE CASCADE,
    user_id           UUID                     NOT NULL REFERENCES users (id),
    role              VARCHAR(8)               NOT NULL,
    status            VARCHAR(16)              NOT NULL,
    captured_by       UUID REFERENCES users (id),
    warning_count     INT                      NOT NULL DEFAULT 0,
    connection_state  VARCHAR(16)              NOT NULL DEFAULT 'CONNECTED',
    disconnected_at   TIMESTAMP WITH TIME ZONE,
    joined_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (game_id, user_id),
    CONSTRAINT chk_players_role CHECK (role IN ('POLICE', 'THIEF')),
    CONSTRAINT chk_players_status CHECK (status IN ('ACTIVE', 'ESCORTED', 'JAILED', 'ELIMINATED')),
    CONSTRAINT chk_players_connection CHECK (connection_state IN ('CONNECTED', 'RECONNECTING', 'LEFT')),
    CONSTRAINT chk_players_warning CHECK (warning_count >= 0)
);
CREATE INDEX idx_game_players_user ON game_players (user_id);

-- 매칭 대기열. 사용자당 1행(동시에 두 번 대기할 수 없음).
CREATE TABLE matchmaking_queue (
    user_id     UUID PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    latitude    DOUBLE PRECISION         NOT NULL,
    longitude   DOUBLE PRECISION         NOT NULL,
    accuracy_m  DOUBLE PRECISION         NOT NULL,
    status      VARCHAR(16)              NOT NULL,
    game_id     UUID REFERENCES games (id),
    joined_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_queue_status CHECK (status IN ('WAITING', 'MATCHED', 'CANCELLED', 'EXPIRED'))
);
CREATE INDEX idx_matchmaking_status_joined ON matchmaking_queue (status, joined_at);

-- 위치 기록. source=MOCK 은 개발자 테스트 좌표(실제 위치와 구분).
CREATE TABLE player_locations (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      UUID                     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    game_id      UUID REFERENCES games (id) ON DELETE SET NULL,
    latitude     DOUBLE PRECISION         NOT NULL,
    longitude    DOUBLE PRECISION         NOT NULL,
    accuracy_m   DOUBLE PRECISION         NOT NULL,
    source       VARCHAR(8)               NOT NULL,
    measured_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_locations_source CHECK (source IN ('GPS', 'MOCK'))
);
CREATE INDEX idx_player_locations_user_received ON player_locations (user_id, received_at);
CREATE INDEX idx_player_locations_game_received ON player_locations (game_id, received_at);

-- 경기 이벤트 로그(체포, 구출, 구역 축소 등). event_data 는 JSON 문자열.
CREATE TABLE game_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id     UUID                     NOT NULL REFERENCES games (id) ON DELETE CASCADE,
    event_type  VARCHAR(32)              NOT NULL,
    event_data  TEXT                     NOT NULL DEFAULT '{}',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_game_events_game_id ON game_events (game_id, id);

-- 경기별 고정 QR 토큰. (game_id, user_id) 당 1개, 토큰은 전체에서 유일.
-- 경기 종료 시 revoked_at 을 채워 무효화한다.
CREATE TABLE qr_tokens (
    id          UUID PRIMARY KEY,
    game_id     UUID                     NOT NULL REFERENCES games (id) ON DELETE CASCADE,
    user_id     UUID                     NOT NULL REFERENCES users (id),
    token       VARCHAR(64)              NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_qr_tokens_token UNIQUE (token),
    CONSTRAINT uq_qr_tokens_game_user UNIQUE (game_id, user_id)
);
