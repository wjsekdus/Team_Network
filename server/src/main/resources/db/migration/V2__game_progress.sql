-- V1 은 수정하지 않고 확장만 한다. PostgreSQL 과 H2(MODE=PostgreSQL) 양쪽에서 동작한다.
-- 설명: docs/architecture/DATABASE.md

-- 경기: 상태 버전(변경 순서 확인), 초기 반경, 다음 미션 예정 시각
ALTER TABLE games ADD COLUMN version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE games ADD COLUMN initial_radius_m DOUBLE PRECISION NOT NULL DEFAULT 500;
ALTER TABLE games ADD COLUMN next_mission_at TIMESTAMP WITH TIME ZONE;

-- 참가자: 경찰의 현재 호송 대상(1명만 저장 가능 → 경찰 1명당 호송 1명), 구역 이탈 시작 시각, 과속 판정 상태
ALTER TABLE game_players ADD COLUMN escorting_user_id UUID;
ALTER TABLE game_players ADD COLUMN out_of_zone_since TIMESTAMP WITH TIME ZONE;
ALTER TABLE game_players ADD COLUMN speed_candidate_count INT NOT NULL DEFAULT 0;
ALTER TABLE game_players ADD COLUMN last_speed_warning_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE game_players ADD COLUMN last_ring_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE game_players ADD CONSTRAINT fk_players_escorting FOREIGN KEY (escorting_user_id) REFERENCES users (id);
-- 한 도둑을 두 경찰이 동시에 호송할 수 없다(NULL 은 여러 개 허용).
ALTER TABLE game_players ADD CONSTRAINT uq_players_escorting UNIQUE (game_id, escorting_user_id);

-- 대기열 위치의 출처(GPS/MOCK) — 매칭 확정 시 경기 최초 위치로 복사한다.
ALTER TABLE matchmaking_queue ADD COLUMN source VARCHAR(8) NOT NULL DEFAULT 'GPS';

-- 진행 중(READY/PLAYING) 경기 참가 기록. user_id 가 기본키이므로 한 사용자가 두 경기에 동시에 들어갈 수 없다.
-- 경기가 끝나면 행을 삭제한다.
CREATE TABLE active_participations (
    user_id    UUID PRIMARY KEY,
    game_id    UUID                     NOT NULL,
    joined_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_active_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_active_game FOREIGN KEY (game_id) REFERENCES games (id) ON DELETE CASCADE
);
CREATE INDEX idx_active_participations_game ON active_participations (game_id);

-- 호송 기록(체포 → 수감 또는 경기 종료). 진행 중 호송은 ended_at IS NULL.
CREATE TABLE escorts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id     UUID                     NOT NULL,
    police_id   UUID                     NOT NULL,
    thief_id    UUID                     NOT NULL,
    started_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at    TIMESTAMP WITH TIME ZONE,
    end_reason  VARCHAR(16),
    CONSTRAINT fk_escorts_game FOREIGN KEY (game_id) REFERENCES games (id) ON DELETE CASCADE,
    CONSTRAINT fk_escorts_police FOREIGN KEY (police_id) REFERENCES users (id),
    CONSTRAINT fk_escorts_thief FOREIGN KEY (thief_id) REFERENCES users (id),
    CONSTRAINT chk_escorts_end CHECK (end_reason IS NULL OR end_reason IN ('JAILED', 'GAME_ENDED'))
);
CREATE INDEX idx_escorts_game ON escorts (game_id);

-- 구역 축소 일정(경기 생성 시 설정값으로 만들고, 미션 실패 시 앞당긴다).
CREATE TABLE game_zone_stages (
    game_id       UUID                     NOT NULL,
    stage_no      INT                      NOT NULL,
    scheduled_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    radius_m      DOUBLE PRECISION         NOT NULL,
    warned_at     TIMESTAMP WITH TIME ZONE,
    applied_at    TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY (game_id, stage_no),
    CONSTRAINT fk_zone_stages_game FOREIGN KEY (game_id) REFERENCES games (id) ON DELETE CASCADE,
    CONSTRAINT chk_zone_stage_radius CHECK (radius_m > 0)
);

-- 도둑 미션.
CREATE TABLE missions (
    id                UUID PRIMARY KEY,
    game_id           UUID                     NOT NULL,
    target_latitude   DOUBLE PRECISION         NOT NULL,
    target_longitude  DOUBLE PRECISION         NOT NULL,
    target_radius_m   DOUBLE PRECISION         NOT NULL,
    started_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    deadline_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    status            VARCHAR(16)              NOT NULL,
    completed_by      UUID,
    ended_at          TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_missions_game FOREIGN KEY (game_id) REFERENCES games (id) ON DELETE CASCADE,
    CONSTRAINT fk_missions_user FOREIGN KEY (completed_by) REFERENCES users (id),
    CONSTRAINT chk_missions_status CHECK (status IN ('ACTIVE', 'COMPLETED', 'FAILED', 'CANCELLED'))
);
CREATE INDEX idx_missions_game ON missions (game_id);

-- 이벤트: 경기 버전과 공개 범위(ALL / POLICE / THIEF / USER=target_user_id 한 명)
ALTER TABLE game_events ADD COLUMN game_version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE game_events ADD COLUMN visibility VARCHAR(8) NOT NULL DEFAULT 'ALL';
ALTER TABLE game_events ADD COLUMN target_user_id UUID;
ALTER TABLE game_events ADD CONSTRAINT chk_events_visibility CHECK (visibility IN ('ALL', 'POLICE', 'THIEF', 'USER'));

-- 경기 결과. game_id 가 기본키이므로 결과는 단 한 번만 저장된다(중복 확정 방지).
CREATE TABLE game_results (
    game_id          UUID PRIMARY KEY,
    result           VARCHAR(16)              NOT NULL,
    end_reason       VARCHAR(40)              NOT NULL,
    decided_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_version  BIGINT                   NOT NULL,
    CONSTRAINT fk_results_game FOREIGN KEY (game_id) REFERENCES games (id) ON DELETE CASCADE,
    CONSTRAINT chk_results_result CHECK (result IN ('POLICE_WIN', 'THIEF_WIN', 'INVALID'))
);

-- QR 스캔 요청 기록. (user_id, request_id) 가 같으면 처음 판정 결과를 돌려준다(네트워크 재전송 중복 방지).
CREATE TABLE scan_requests (
    user_id      UUID                     NOT NULL,
    request_id   VARCHAR(64)              NOT NULL,
    game_id      UUID                     NOT NULL,
    kind         VARCHAR(8)               NOT NULL,
    result_json  TEXT                     NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (user_id, request_id),
    CONSTRAINT fk_scan_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_scan_game FOREIGN KEY (game_id) REFERENCES games (id) ON DELETE CASCADE,
    CONSTRAINT chk_scan_kind CHECK (kind IN ('CAPTURE', 'RESCUE'))
);

CREATE INDEX idx_player_locations_game_user_measured ON player_locations (game_id, user_id, measured_at);
